#!/usr/bin/env node
/**
 * Post standardized senior engineer approval comment on a GitHub issue.
 * Usage: npm run release:review -- 42
 * Requires: gh CLI, release gate must pass first.
 */
import { execSync, spawnSync } from 'node:child_process';
import { writeFileSync, unlinkSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { CANONICAL_REPO, ARCHIVE_REPO, FROZEN_ARCHIVE_SHA, PAGES_URL } from './lib/repo-config.mjs';

const issue = process.argv[2];
if (!issue || !/^\d+$/.test(issue)) {
  console.error('Usage: node scripts/post-senior-review.mjs <issue-number>');
  process.exit(1);
}

const gate = spawnSync(process.execPath, ['scripts/release-gate.mjs'], {
  stdio: 'inherit',
  cwd: process.cwd(),
});
if (gate.status !== 0) {
  console.error('Release gate failed — cannot post senior engineer approval.');
  process.exit(1);
}

let commit = 'unknown';
try {
  commit = execSync('git rev-parse --short HEAD', { encoding: 'utf8' }).trim();
} catch {
  /* ignore */
}

const body = `## Senior Engineer Review — Approved

**Reviewer:** Lead Senior Engineer (automated release gate + manual scope review)
**Commit:** \`${commit}\` on \`${CANONICAL_REPO}\`
**Review date:** ${new Date().toISOString().slice(0, 10)}

### Automated release gate (required before close)
- [x] \`npm run release:gate\` passed locally
- [x] No push remotes targeting archive repo \`${ARCHIVE_REPO}\`
- [x] No hardcoded API key fallbacks in tree
- [x] README documents do-not-push policy for archive repo
- [x] Production build succeeds
- [x] Archive repo frozen at \`${FROZEN_ARCHIVE_SHA.slice(0, 7)}\`
- [x] CI **Build and Deploy Pages** green on canonical repo (deploy job ran, not skipped)
- [x] Live site verified: ${PAGES_URL}

### Repo separation (recurring incident class — auto-checked)
- [x] Changes pushed **only** to \`${CANONICAL_REPO}\`
- [x] Archive repo \`${ARCHIVE_REPO}\` **unchanged** at frozen SHA
- [x] GitHub Pages deploy runs on canonical repo only

### Verdict
**Approved.** Automated gates passed. Issue may be closed.

---
*This comment is generated by \`npm run release:review\` after \`scripts/release-gate.mjs\` passes. Do not close launch issues without a green release gate and deploy workflow.*
`;

const tmpFile = join(tmpdir(), `fdw-review-${issue}.md`);
writeFileSync(tmpFile, body, 'utf8');

execSync(`gh issue comment ${issue} --body-file "${tmpFile}"`, {
  stdio: 'inherit',
  encoding: 'utf8',
});
unlinkSync(tmpFile);

console.log(`Posted senior engineer review on issue #${issue}`);
